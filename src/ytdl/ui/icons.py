STROKE = {"check": 3}  # 小さく描くものだけ太く


@lru_cache(maxsize=None)
def icon(name: str, color: str = "#85858b", size: int = 18) -> QIcon:
    stroke = STROKE.get(name, 1.5)
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
           f'stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{_PATHS[name]}</svg>')
    renderer = QSvgRenderer(QByteArray(svg.encode()))
    result = QIcon()
    for scale in (1, 2):
        pm = QPixmap(size * scale, size * scale)
        pm.fill(Qt.transparent)
        p = QPainter(pm)
        renderer.render(p, QRectF(0, 0, size * scale, size * scale))
        p.end()
        pm.setDevicePixelRatio(scale)
        result.addPixmap(pm)
    return result


@lru_cache(maxsize=None)
def app_icon() -> QIcon:
    ico = ASSETS_DIR / "app.ico"
    return QIcon(str(ico)) if ico.exists() else QIcon(str(ASSETS_DIR / "app.png"))
